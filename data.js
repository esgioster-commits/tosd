// Helper to get all unique swimmers
function getAllSwimmers() {
  const swimmerMap = new Map();

  MEET_DATA.forEach(event => {
    event.heats.forEach(heat => {
      heat.entries.forEach(entry => {
        const cleanName = entry.name.trim();
        if (!swimmerMap.has(cleanName)) {
          swimmerMap.set(cleanName, {
            name: cleanName,
            age: entry.age,
            team: entry.team,
            events: []
          });
        }
        
        swimmerMap.get(cleanName).events.push({
          eventId: event.eventId,
          eventName: event.name,
          session: event.session,
          stroke: event.stroke,
          distance: event.distance,
          heatNumber: heat.heatNumber,
          totalHeats: heat.totalHeats,
          startTime: heat.startTime,
          lane: entry.lane,
          seedTime: entry.seedTime,
          heatEntries: heat.entries // All swimmers in this heat for matchup
        });
      });
    });
  });

  return Array.from(swimmerMap.values()).sort((a, b) => a.name.localeCompare(b.name));
}

// Helper to get all teams
function getAllTeams() {
  const teams = new Set();
  MEET_DATA.forEach(event => {
    event.heats.forEach(heat => {
      heat.entries.forEach(entry => {
        if (entry.team) teams.add(entry.team);
      });
    });
  });
  return Array.from(teams).sort();
}
